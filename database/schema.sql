CREATE TABLE IF NOT EXISTS user (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(32) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role ENUM('user','admin') NOT NULL DEFAULT 'user'
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS diamonml (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 jumlahdm INT UNSIGNED NOT NULL,
 hargadm DECIMAL(12,2) NOT NULL
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS diamonff LIKE diamonml;
CREATE TABLE IF NOT EXISTS diamonpubg LIKE diamonml;
CREATE TABLE IF NOT EXISTS transaksi (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 jumlahdm INT UNSIGNED NOT NULL,
 hargadm DECIMAL(12,2) NOT NULL,
 game VARCHAR(100) NOT NULL,
 idusergame VARCHAR(100) NOT NULL,
 name VARCHAR(100) NOT NULL
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
